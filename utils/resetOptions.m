function  resetOptions(app)
    disable_properties(app)
    app.LinksEditField.Value = 0;
    app.MinangleEditField.Value = 0;
    app.MaxangleEditField.Value = 0;
    app.MinlengthEditField.Value=0;
    app.MaxlengthEditField.Value = 0;
